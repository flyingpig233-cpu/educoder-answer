#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
void hailstone(int n) {
    int count = 0;
    printf("Hailstone generated by %d:\n", n);
    for (;;) {
        printf("%5d", n);
        count++;
        if (n == 1) {
            putchar('\n');
            break;
        }
        if (count % 6 == 0)
            putchar('\n');
        n = n % 2 ? 3 * n + 1 : n / 2;
    }
    printf("Number of hailstone generated:%d", count);
}
int main(void) {
    int n;
    printf("input a number:");
    scanf("%d", &n);
    hailstone(n);
    return 0;
}
